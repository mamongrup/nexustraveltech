const supportedCurrencies = ["TRY", "EUR", "USD", "GBP", "RUB", "AED"];
const defaultLanguage = "tr";
const defaultCurrency = "TRY";

function getStoredChoice(key, fallback, allowed) {
  const params = new URLSearchParams(window.location.search);
  const urlValue = params.get(key);
  const storedValue = window.localStorage.getItem(`nexus-${key}`);
  const value = urlValue || storedValue || fallback;

  return allowed.includes(value) ? value : fallback;
}

function setQueryParam(key, value) {
  const url = new URL(window.location.href);
  url.searchParams.set(key, value);
  window.history.replaceState({}, "", url);
}

function applyLanguage(language) {
  const active = locales[language] || locales[defaultLanguage];
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (active[key]) node.textContent = active[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    const key = node.getAttribute("data-i18n-html");
    if (active[key]) node.innerHTML = active[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.getAttribute("data-i18n-placeholder");
    if (active[key]) node.setAttribute("placeholder", active[key]);
  });
}

function applyCurrency(currency) {
  document.querySelectorAll("[data-currency-code]").forEach((node) => {
    node.textContent = currency;
  });

  document.querySelectorAll("[data-currency-option]").forEach((node) => {
    const isActive = node.getAttribute("data-currency-option") === currency;
    node.classList.toggle("active", isActive);
    node.setAttribute("aria-current", isActive ? "true" : "false");
  });
}

function boot() {
  const languageSelect = document.querySelector("#site-language");
  const currencySelect = document.querySelector("#site-currency");
  const language = getStoredChoice("lang", defaultLanguage, Object.keys(locales));
  const currency = getStoredChoice("currency", defaultCurrency, supportedCurrencies);

  if (languageSelect) languageSelect.value = language;
  if (currencySelect) currencySelect.value = currency;
  applyLanguage(language);
  applyCurrency(currency);

  if (languageSelect) {
    languageSelect.addEventListener("change", (event) => {
      const nextLanguage = event.target.value;
      window.localStorage.setItem("nexus-lang", nextLanguage);
      document.cookie = `nexus-language=${nextLanguage};path=/;max-age=31536000;SameSite=Lax`;
      setQueryParam("lang", nextLanguage);
      applyLanguage(nextLanguage);
    });
  }

  if (currencySelect) {
    currencySelect.addEventListener("change", (event) => {
      const nextCurrency = event.target.value;
      window.localStorage.setItem("nexus-currency", nextCurrency);
      document.cookie = `nexus-currency=${nextCurrency};path=/;max-age=31536000;SameSite=Lax`;
      setQueryParam("currency", nextCurrency);
      applyCurrency(nextCurrency);
    });
  }
}

document.addEventListener("DOMContentLoaded", boot);
